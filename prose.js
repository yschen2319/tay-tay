/* ---------- 合并：把文案覆盖进 albums ---------- */
(function applyProse() {
  if (typeof albums === "undefined") return;
  albums.forEach((album) => {
    const prose = albumProse[album.id];
    if (!prose) return;
    if (prose.thesis) album.thesis = prose.thesis;
    if (prose.context) album.context = prose.context;
    if (prose.life) album.life = prose.life;
    if (!prose.songs) return;
    [...album.hits, ...album.deeps].forEach((song) => {
      const entry = prose.songs[song.title];
      if (!entry) return;
      if (entry.analysis) song.analysis = entry.analysis;
      if (entry.life) song.life = entry.life;
    });
  });
})();
